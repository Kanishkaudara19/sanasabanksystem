    private void okbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_okbtnActionPerformed
        if(llimitbox.getText().isEmpty() || mandatorybox.getText().isEmpty() || securitiesbox.getText().isEmpty() || sharebox.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Some feilds are Empty");
        }else{
            int share = Integer.parseInt(sharebox.getText());
            int limit = Integer.parseInt(llimitbox.getText());
            int manda = Integer.parseInt(mandatorybox.getText());
            int sec = Integer.parseInt(securitiesbox.getText());
            int from = Integer.parseInt(frombox.getText());
            int to = Integer.parseInt(tobox.getText());
            int interest = Integer.parseInt(interestbox.getText());
            int cal = Integer.parseInt(installcalbox.getText());

            try {
                String sql = "UPDATE admin SET share='"+share+"',mandatory='"+manda+"',securities='"+sec+"',loan_limit='"+limit+"',frominstallment='"+from+"',toinstallment='"+to+"',callimit='"+cal+"',interest='"+interest+"'";
                pst = con.prepareStatement(sql);
                pst.execute();
                JOptionPane.showMessageDialog(null,"updated succesfull");
            } catch (Exception e) {
            }
        }
    }//GEN-LAST:event_okbtnActionPerformed

