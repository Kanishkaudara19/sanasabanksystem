    public void setdata(){
        try {
           pst = con.prepareStatement("SElECT share,mandatory,securities,loan_limit,frominstallment,toinstallment,callimit,interest FROM admin ");
           rs = pst.executeQuery();
           rs.next();
           int limit = rs.getInt("loan_limit");
           int from = rs.getInt("frominstallment");
           int to = rs.getInt("toinstallment");
           int share = rs.getInt("share");
           int manda = rs.getInt("mandatory");
           int sec = rs.getInt("securities");
           int cal = rs.getInt("callimit");
           int interest = rs.getInt("interest");
           
            tobox.setText(String.valueOf(to));
            frombox.setText(String.valueOf(from));
            llimitbox.setText(String.valueOf(limit));
            sharebox.setText(String.valueOf(share));
            mandatorybox.setText(String.valueOf(manda));
            securitiesbox.setText(String.valueOf(sec));
            interestbox.setText(String.valueOf(interest));
            installcalbox.setText(String.valueOf(cal));
        } catch (Exception e) {
        }
    }

