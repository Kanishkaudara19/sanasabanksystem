    private void llimitboxKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_llimitboxKeyPressed
        String   phone =llimitbox.getText();
        int length = phone.length();
        char c = evt.getKeyChar();

        if ( evt.getKeyChar()>='0' &&  evt.getKeyChar()<='9'){
            if (length<10){
                llimitbox.setEditable(true);
            }else{
                llimitbox.setEditable(false);
            }

        }else{
            if (evt.getExtendedKeyCode()==KeyEvent.VK_BACK_SPACE){
                llimitbox.setEditable(true);
            }else{
                llimitbox.setEditable(false);
            }
        }
    }//GEN-LAST:event_llimitboxKeyPressed

