    public void phoneno(){
         String   phone =phonenobox.getText();
        int length = phone.length();
        if(phone.isEmpty()){
           phonenobox.setBackground(Color.WHITE);
        }else{
            if(length<10){
              addbtn.setEnabled(false);
              phonenobox.setBackground(Color.RED);
              updatebtn.setEnabled(false);
            }else{
                if(length==10){
                    addbtn.setEnabled(true);
                    updatebtn.setEnabled(true);
                   phonenobox.setBackground(Color.GREEN);
                }else{
                    addbtn.setEnabled(false);
                    updatebtn.setEnabled(false);
                }
            }
        }
    }

     public void setDateTime() {
        
        Calendar c = Calendar.getInstance();
        hour= c.get(Calendar.HOUR_OF_DAY);
        if (hour >12)
            hour=hour -12;
        minute= c.get(Calendar.MINUTE);
        second= c.get(Calendar.SECOND);
        year= c.get(Calendar.YEAR);
        month= c.get(Calendar.MONTH);
        day= c.get(Calendar.DAY_OF_MONTH);
        SimpleDateFormat sdf = new SimpleDateFormat("hh:mm:ss a");
        SimpleDateFormat df = new SimpleDateFormat("dd/MM/yyyy");
        Date dat = c.getTime();
        timestr=sdf.format(dat);
        yearstr=df.format(dat);
        mtimebox.setText(timestr);
        mdatebox.setText(yearstr);
               

    }
