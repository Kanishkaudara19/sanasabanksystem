    private void findbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_findbtnActionPerformed
        if(accnobox.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Please Enter Account Number", "Error", JOptionPane.ERROR_MESSAGE);
        }else{
            try {
                int accno = Integer.parseInt(accnobox.getText());
                if(accno>=1 && accno<=500){
                    pst = con.prepareStatement("SELECT accno,name,balance FROM memberacc WHERE accno = ?");
                    pst.setInt(1, accno);
                    rs = pst.executeQuery();
                    if(rs.next()==false){
                        JOptionPane.showMessageDialog(null, "Search item not found", "Error", JOptionPane.ERROR_MESSAGE);
                    }else{
                        String fname =  rs.getString("name");
                        String id =  rs.getString("accno");
                        String balance =  rs.getString("balance");

                        typebox.setText("Member");
                        namebox.setText(fname);
                        idbox.setText(id);
                        balancebox.setText(balance);
                    }
                }else{
                    if(accno>=501 && accno<=700){
                        pst = con.prepareStatement("SELECT accno,name,balance FROM childacc WHERE accno = ?");
                        pst.setInt(1, accno);
                        rs = pst.executeQuery();
                        if(rs.next()==false){
                            JOptionPane.showMessageDialog(null, "Search item not found", "Error", JOptionPane.ERROR_MESSAGE);
                        }else{
                            String fname =  rs.getString("name");
                            String id =  rs.getString("accno");
                            String balance =  rs.getString("balance");

                            typebox.setText("Child");
                            namebox.setText(fname);
                            idbox.setText(id);
                            balancebox.setText(balance);
                        }
                    }else{
                        pst = con.prepareStatement("SELECT accno,name,balance FROM nonmemberacc WHERE accno = ?");
                        pst.setInt(1, accno);
                        rs = pst.executeQuery();
                        if(rs.next()==false){
                            JOptionPane.showMessageDialog(null, "Search item not found", "Error", JOptionPane.ERROR_MESSAGE);
                        }else{
                            String fname =  rs.getString("name");
                            String id =  rs.getString("accno");
                            String balance =  rs.getString("balance");

                            typebox.setText("Non-Member");
                            namebox.setText(fname);
                            idbox.setText(id);
                            balancebox.setText(balance);
                        }
                    }
                }
            } catch (Exception e) {
            }
        }
        accnobox.setText("");
    }//GEN-LAST:event_findbtnActionPerformed

