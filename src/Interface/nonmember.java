                    String soname =  rs.getString("soname");
                    String soaddress =  rs.getString("soaddress");
                    String phoneno =  rs.getString("phoneno");
                    String relation =  rs.getString("relationship");

                    ((JTextField)datechooser.getDateEditor().getUiComponent()).setText(date);
                    nonidbox.setText(id);
                    fnamebox.setText(fname);
                    lnamebox.setText(lname);
