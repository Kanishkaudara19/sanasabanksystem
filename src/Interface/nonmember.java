    private void nonidboxKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_nonidboxKeyPressed
        String   phone =nonidbox.getText();
        int length = phone.length();
        char c = evt.getKeyChar();

        if ( evt.getKeyChar()>='0' &&  evt.getKeyChar()<='9'){
            if (length<3){
                nonidbox.setEditable(true);
            }else{
                nonidbox.setEditable(false);

            }

        }else{
            if (evt.getExtendedKeyCode()==KeyEvent.VK_BACK_SPACE){
                nonidbox.setEditable(true);
            }else{
                nonidbox.setEditable(false);
            }
        }
    }//GEN-LAST:event_nonidboxKeyPressed

