    private void phonenoboxKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_phonenoboxKeyPressed
        String   phone =phonenobox.getText();
        int length = phone.length();
        char c = evt.getKeyChar();

        if ( evt.getKeyChar()>='0' &&  evt.getKeyChar()<='9'){
            if (length<10){
                phonenobox.setEditable(true);
            }else{
                phonenobox.setEditable(false);
            }
        }else{
            if (evt.getExtendedKeyCode()==KeyEvent.VK_BACK_SPACE){
                phonenobox.setEditable(true);
            }else{
                phonenobox.setEditable(false);
            }
        }
    }//GEN-LAST:event_phonenoboxKeyPressed

