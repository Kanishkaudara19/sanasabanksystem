    private void searchbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchbtnActionPerformed

        if(searchbox.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Please Enter Non-Member ID","Information",JOptionPane.INFORMATION_MESSAGE);
        }else{
            try {
                pst = con.prepareStatement("SElECT childid,fname,lname,dob,address,trusteename,trusteeaddress,trusteenic,trusteephoneno FROM child WHERE childid=?");
                int search = Integer.parseInt(searchbox.getText());
                pst.setInt(1, search);
                rs = pst.executeQuery();

                if(rs.next()==false){
                    JOptionPane.showMessageDialog(null, "Search item not found","Information",JOptionPane.INFORMATION_MESSAGE);
                }else{
                    String id = rs.getString("childid");
                    String fname =  rs.getString("fname");
                    String lname =  rs.getString("lname");
                    String nic =  rs.getString("trusteenic");
                    String address =  rs.getString("address");
                    String date = rs.getString("dob");
                    String tname =  rs.getString("trusteename");
                    String taddress =  rs.getString("trusteeaddress");
                    String phoneno =  rs.getString("trusteephoneno");

                    ((JTextField)dobbox.getDateEditor().getUiComponent()).setText(date);
                    childidbox.setText(id);
                    fnamebox.setText(fname);
                    lnamebox.setText(lname);
                    nicbox.setText(nic);
                    caddressbox.setText(address);
                    tnamebox.setText(tname);
                    taddressbox.setText(taddress);
                    phonenobox.setText(phoneno);
                }
            } catch (Exception e) {
            }
        }
    }//GEN-LAST:event_searchbtnActionPerformed

