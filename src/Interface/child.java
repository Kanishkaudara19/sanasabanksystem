    public void phoneno(){
         String   phone =phonenobox.getText();
        int length = phone.length();
        if(phone.isEmpty()){
           phonenobox.setBackground(Color.WHITE);
        }else{
            if(length<10){
                addbtn.setEnabled(false);
              phonenobox.setBackground(Color.RED);
              updatebtn.setEnabled(false);
            }else{
                if(length==10){
                    addbtn.setEnabled(true);
                    updatebtn.setEnabled(true);
                   phonenobox.setBackground(Color.GREEN);
                }else{
                    addbtn.setEnabled(false);
                    updatebtn.setEnabled(false);
                }
            }
        }
    }
    
